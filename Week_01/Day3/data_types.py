# Demonstrating basic data types in Python

a = 1         # a is an integer
b = 1         # b is an integer

# print(a)    # this line is commented and won't run

print(a + b)               # prints the sum of a and b
print(type(a + b))         # prints the type (int) of the result

c = "2"       # c is a string
d = "2"       # d is a string

print(c + d)               # prints the concatenation of c and d ("22")
print(type(c + d))         # prints the type (str) of the result
